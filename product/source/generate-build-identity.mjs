import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, resolve, sep } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const outputPath = join(root, 'build-identity.js');
const excluded = new Set(['build-identity.js']);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const absolute = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute));
    else if (entry.isFile()) files.push(absolute);
  }
  return files;
}

export async function computeBuildId() {
  const files = (await walk(root))
    .map(absolute => ({ absolute, path: relative(root, absolute).split(sep).join('/') }))
    .filter(file => !excluded.has(file.path))
    .sort((a, b) => a.path.localeCompare(b.path));
  const aggregate = createHash('sha256');
  for (const file of files) {
    const bytes = await readFile(file.absolute);
    const blob = createHash('sha1')
      .update('blob ' + bytes.length + '\0')
      .update(bytes)
      .digest('hex');
    aggregate.update(file.path + '\0' + blob + '\n');
  }
  return 'src-' + aggregate.digest('hex').slice(0, 24);
}

export function renderBuildIdentity(buildId) {
  return [
    '// Generated by generate-build-identity.mjs. Do not hand-edit.',
    '// Fingerprint covers every product/source file except this generated output.',
    "self.INK_BUILD_ID = '" + buildId + "';",
    ''
  ].join('\n');
}

export async function generateBuildIdentity({ check = false } = {}) {
  const buildId = await computeBuildId();
  const expected = renderBuildIdentity(buildId);
  if (check) {
    const actual = await readFile(outputPath, 'utf8').catch(() => '');
    if (actual !== expected) throw new Error('build-identity.js is stale; run node product/source/generate-build-identity.mjs');
  } else {
    await writeFile(outputPath, expected);
  }
  return buildId;
}

const invokedPath = process.argv[1] ? resolve(process.argv[1]) : '';
if (invokedPath === fileURLToPath(import.meta.url)) {
  const buildId = await generateBuildIdentity({ check: process.argv.includes('--check') });
  process.stdout.write(buildId + '\n');
}
